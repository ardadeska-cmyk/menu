function Window:_setupWindowDrag()
	local dragging = false
	local dragStart = Vector3.zero
	local startOffset = Vector2.zero
	self._cleanup:Give(self._header.InputBegan:Connect(function(inputObject: InputObject)
		if not Input.IsPrimary(inputObject) or self._deviceMode == "Phone" or self._draggable == false then
			return
		end
		dragging = true
		dragStart = inputObject.Position
		startOffset = Vector2.new(self._host.Position.X.Offset, self._host.Position.Y.Offset)
	end))
	self._cleanup:Give(UserInputService.InputChanged:Connect(function(inputObject: InputObject)
		if dragging and Input.IsPointerMove(inputObject) then
			local delta3 = inputObject.Position - dragStart
			self._responsive:MoveWindowFrom(startOffset, Vector2.new(delta3.X, delta3.Y))
		end
	end))
	self._cleanup:Give(UserInputService.InputEnded:Connect(function(inputObject: InputObject)
		if Input.IsPrimary(inputObject) then
			dragging = false
		end
	end))
end

function Window:_setupMobileDrag()
	local button = self._mobileToggle
	local success, detectorOrError = pcall(function()
		local detector = Instance.new("UIDragDetector")
		local detectorAny = detector :: any
		detectorAny.DragStyle = Enum.UIDragDetectorDragStyle.TranslatePlane
		detectorAny.ResponseStyle = Enum.UIDragDetectorResponseStyle.Offset
		detectorAny.BoundingUI = self._persistentRoot
		detectorAny.BoundingBehavior = Enum.UIDragDetectorBoundingBehavior.EntireObject
		detector.Parent = button
		return detector
	end)
	if success then
		local detector = detectorOrError :: any
		local startPosition = button.Position
		self._cleanup:Give(detector.DragStart:Connect(function()
			startPosition = button.Position
			self._mobileDragged = false
		end))
		self._cleanup:Give(button:GetPropertyChangedSignal("Position"):Connect(function()
			if math.abs(button.Position.X.Offset - startPosition.X.Offset) > 4
				or math.abs(button.Position.Y.Offset - startPosition.Y.Offset) > 4
			then
				self._mobileDragged = true
			end
		end))
		self._cleanup:Give(detector.DragEnd:Connect(function()
			self._responsive:ClampMobileButton()
			task.defer(function()
				self._mobileDragged = false
			end)
		end))
		return
	end

	warn("[Endware] UIDragDetector was unavailable; using the fallback mobile drag controller: " .. tostring(detectorOrError))
	local dragging = false
	local startInput = Vector3.zero
	local startPosition = Vector2.zero
	self._cleanup:Give(button.InputBegan:Connect(function(inputObject: InputObject)
		if Input.IsPrimary(inputObject) then
			dragging = true
			self._mobileDragged = false
			startInput = inputObject.Position
			startPosition = Vector2.new(button.Position.X.Offset, button.Position.Y.Offset)
		end
	end))
	self._cleanup:Give(UserInputService.InputChanged:Connect(function(inputObject: InputObject)
		if dragging and Input.IsPointerMove(inputObject) then
			local delta = inputObject.Position - startInput
			if math.abs(delta.X) > 4 or math.abs(delta.Y) > 4 then
				self._mobileDragged = true
			end
			button.Position = UDim2.fromOffset(startPosition.X + delta.X, startPosition.Y + delta.Y)
			self._responsive:ClampMobileButton()
		end
	end))
	self._cleanup:Give(UserInputService.InputEnded:Connect(function(inputObject: InputObject)
		if Input.IsPrimary(inputObject) then
			dragging = false
			task.defer(function()
				self._mobileDragged = false
			end)
		end
	end))
end

function Window.new(options: any?): any
	options = options or {}
	local localPlayer = Players.LocalPlayer
