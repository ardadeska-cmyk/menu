	}) :: ScreenGui
	pcall(function()
		screenGui.ScreenInsets = Enum.ScreenInsets.DeviceSafeInsets
		screenGui.SafeAreaCompatibility = Enum.SafeAreaCompatibility.FullscreenExtension
		screenGui.ClipToDeviceSafeArea = true
	end)

	local self = setmetatable({
		_cleanup = cleanup,
		_screenGui = screenGui,
		_bindings = {},
		_theme = theme,
		_tabs = {},
		_activeTab = nil,
		_tabOrder = 0,
		_notificationOrder = 1,
		_dropdownMenu = nil,
		_dropdownCleanup = nil,
		_destroyed = false,
		_deviceMode = "Desktop",
		_draggable = options.Draggable ~= false,
		_mobileToggleEnabled = options.MobileToggle ~= false,
		_mobileDragged = false,
		_positionWasDragged = false,
		_defaultYOffset = math.clamp(tonumber(options.VerticalOffset) or 28, -80, 120),
		_backdropTransparency = math.clamp(tonumber(options.BackdropTransparency) or 0.56, 0, 1),
	}, Window)
	cleanup:Give(screenGui)

	local persistentRoot = Create("Frame", {
		Name = "PersistentRoot",
		Size = UDim2.fromScale(1, 1),
		BackgroundTransparency = 1,
		BorderSizePixel = 0,
		ClipsDescendants = false,
		ZIndex = 700,
		Parent = screenGui,
	}) :: Frame
	local safeRoot = Create("Frame", {
		Name = "SafeRoot",
		Size = UDim2.fromScale(1, 1),
		BackgroundTransparency = 1,
		BorderSizePixel = 0,
		ClipsDescendants = false,
		ZIndex = 1,
		Parent = screenGui,
	}) :: Frame
	local backdrop = Create("TextButton", {
		Name = "Backdrop",
		Size = UDim2.fromScale(1, 1),
		BackgroundTransparency = self._backdropTransparency,
		BorderSizePixel = 0,
		AutoButtonColor = false,
		Text = "",
		ZIndex = 2,
		Parent = safeRoot,
