__modules['Utility/Math'] = function(__require)

local Math = {}

function Math.RoundToStep(value: number, step: number): number
	if step <= 0 then
		return value
	end
	return math.round(value / step) * step
end

function Math.ClampPoint(point: Vector2, size: Vector2, bounds: Vector2, margin: number?): Vector2
	local safeMargin = margin or 8
	local maxX = math.max(safeMargin, bounds.X - size.X - safeMargin)
	local maxY = math.max(safeMargin, bounds.Y - size.Y - safeMargin)
	return Vector2.new(
		math.clamp(point.X, safeMargin, maxX),
		math.clamp(point.Y, safeMargin, maxY)
	)
end

return Math

end

