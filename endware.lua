__modules['Components/ControlBase'] = function(__require)

local Cleanup = __require("Core/Cleanup")

local ControlBase = {}
ControlBase.__index = ControlBase

export type Options = {
	Root: GuiObject,
	Window: any,
	Value: any,
	Render: ((any, boolean) -> ())?,
	Callback: ((...any) -> ())?,
	Normalize: ((any) -> any)?,
}

function ControlBase.new(options: Options): any
	local cleanup = Cleanup.new()
	cleanup:Give(options.Root)
	options.Window._cleanup:Give(cleanup)
	local self = setmetatable({
		_cleanup = cleanup,
		_root = options.Root,
		_window = options.Window,
		_value = options.Value,
		_render = options.Render,
		_callback = options.Callback,
		_normalize = options.Normalize,
		_disabled = false,
		_destroyed = false,
	}, ControlBase)
	if self._render then
		self._render(self._value, false)
	end
	return self
end

function ControlBase:Get(): any
	return self._value
end

function ControlBase:Set(value: any, setOptions: any?)
	if self._destroyed then
		return self
	end
	if self._normalize then
		value = self._normalize(value)
	end
	self._value = value
	if self._render then
		self._render(value, self._disabled)
	end
	if setOptions and setOptions.FireCallback == true and self._callback then
		self._window:_safeCall(self._callback, value)
	end
	return self
end

function ControlBase:_SetFromUser(value: any, ...: any)
	if self._destroyed or self._disabled then
		return
	end
	if self._normalize then
		value = self._normalize(value)
	end
	self._value = value
	if self._render then
		self._render(value, self._disabled)
	end
	if self._callback then
		self._window:_safeCall(self._callback, value, ...)
	end
end

function ControlBase:SetDisabled(disabled: boolean)
	self._disabled = disabled
	self._root.Active = not disabled
	if self._render then
		self._render(self._value, disabled)
	end
	return self
end

function ControlBase:SetVisible(visible: boolean)
	self._root.Visible = visible
	return self
end

function ControlBase:Destroy()
	if self._destroyed then
		return
	end
	self._destroyed = true
	self._cleanup:Destroy()
end

return ControlBase

end

