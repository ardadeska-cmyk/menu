__modules['Core/Cleanup'] = function(__require)

local Cleanup = {}
Cleanup.__index = Cleanup

type Cleanup = typeof(setmetatable({} :: {
	_tasks: {any},
	_destroyed: boolean,
}, Cleanup))

local function dispose(taskValue: any)
	local valueType = typeof(taskValue)
	if valueType == "RBXScriptConnection" then
		if taskValue.Connected then
			taskValue:Disconnect()
		end
	elseif valueType == "Instance" then
		taskValue:Destroy()
	elseif valueType == "function" then
		taskValue()
	elseif valueType == "Tween" then
		taskValue:Cancel()
	elseif type(taskValue) == "table" then
		if type(taskValue.Destroy) == "function" then
			taskValue:Destroy()
		elseif type(taskValue.Cleanup) == "function" then
			taskValue:Cleanup()
		elseif type(taskValue.Cancel) == "function" then
			taskValue:Cancel()
		end
	end
end

function Cleanup.new(): Cleanup
	return setmetatable({
		_tasks = {},
		_destroyed = false,
	}, Cleanup)
end

function Cleanup:Give<T>(taskValue: T): T
	if self._destroyed then
		dispose(taskValue)
		return taskValue
	end
	table.insert(self._tasks, taskValue)
	return taskValue
end

function Cleanup:Cleanup()
	if self._destroyed then
		return
	end
	for index = #self._tasks, 1, -1 do
		local taskValue = self._tasks[index]
		self._tasks[index] = nil
		local ok, message = pcall(dispose, taskValue)
		if not ok then
			warn("[Endware] Cleanup task failed: " .. tostring(message))
		end
	end
end

function Cleanup:Destroy()
	if self._destroyed then
		return
	end
	self:Cleanup()
	self._destroyed = true
end

return Cleanup

end

