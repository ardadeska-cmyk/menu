		if self._cameraConnection then
			self._cameraConnection:Disconnect()
			self._cameraConnection = nil
		end
		local nextCamera = Workspace.CurrentCamera
		if nextCamera then
			self._cameraConnection = window._cleanup:Give(nextCamera:GetPropertyChangedSignal("ViewportSize"):Connect(function()
				self:Update()
			end))
		end
		self:Update()
	end))
	task.defer(function()
		self:Update()
	end)
	return self
end

function ResponsiveController:GetMode(): string
	return self._mode
end

function ResponsiveController:Update()
	local window = self._window
	local camera = Workspace.CurrentCamera
	if not camera or not window._host.Parent then
		return
	end
	local viewport = camera.ViewportSize
	local touch = UserInputService.TouchEnabled
	local phone = viewport.X < 680 or (touch and math.min(viewport.X, viewport.Y) < 560)
	local tablet = not phone and (touch or viewport.X < 1050)
	self._mode = if phone then "Phone" elseif tablet then "Tablet" else "Desktop"
	window._deviceMode = self._mode

	local width: number
	local height: number
	if phone then
		width = math.floor(viewport.X * 0.94)
		height = math.floor(viewport.Y * 0.82)
	elseif tablet then
		width = math.floor(math.min(730, viewport.X * 0.9))
		height = math.floor(math.min(590, viewport.Y * 0.84))
	else
		width = math.floor(math.min(730, viewport.X * 0.76))
		height = math.floor(math.min(500, viewport.Y * 0.76))
	end
	width = math.clamp(width, math.min(320, viewport.X - 16), math.max(320, viewport.X - 16))
	height = math.clamp(height, math.min(380, viewport.Y - 16), math.max(380, viewport.Y - 16))
	window._host.Size = UDim2.fromOffset(width, height)

	local accentRailHeight = 5
	local headerHeight = if phone then 62 else 78
	local tabsHeight = if phone then 52 else 58
	local headerTop = accentRailHeight
	local tabsTop = headerTop + headerHeight
	local contentTop = tabsTop + tabsHeight

	window._header.Position = UDim2.fromOffset(0, headerTop)
	window._header.Size = UDim2.new(1, 0, 0, headerHeight)
	window._tabsBar.Position = UDim2.fromOffset(0, tabsTop)
	window._tabsBar.Size = UDim2.new(1, 0, 0, tabsHeight)
	window._contentViewport.Position = UDim2.fromOffset(0, contentTop)
	window._contentViewport.Size = UDim2.new(1, 0, 1, -contentTop)
	window._subtitle.Visible = not phone
	window._keyHint.Visible = not phone
	window._title.Position = if phone then UDim2.fromOffset(60, 9) else UDim2.fromOffset(72, 13)
	window._title.Size = if phone then UDim2.new(1, -112, 0, 42) else UDim2.new(1, -230, 0, 28)
	window._logo.Position = if phone then UDim2.fromOffset(14, 10) else UDim2.fromOffset(19, 17)
	window._close.Position = UDim2.new(1, -16, 0.5, 0)
	window._notificationHost.Size = UDim2.fromOffset(math.min(340, viewport.X - 24), math.min(520, viewport.Y - 24))

	if not window._positionWasDragged then
		local yOffset = if phone then 8 else window._defaultYOffset
		window._host.Position = UDim2.new(0.5, 0, 0.5, yOffset)
	end

	self:ClampWindow()
	self:ClampMobileButton()
end

function ResponsiveController:ClampWindow()
	local window = self._window
	local rootSize = window._safeRoot.AbsoluteSize
	local hostSize = window._host.AbsoluteSize
	if rootSize.X <= 0 or rootSize.Y <= 0 then
		return
	end
	local maxX = math.max(0, (rootSize.X - hostSize.X) * 0.5 - 8)
	local maxY = math.max(0, (rootSize.Y - hostSize.Y) * 0.5 - 8)
	local current = window._host.Position
	window._host.Position = UDim2.new(
		0.5,
		math.clamp(current.X.Offset, -maxX, maxX),
		0.5,
		math.clamp(current.Y.Offset, -maxY, maxY)
	)
end

function ResponsiveController:MoveWindowFrom(startOffset: Vector2, delta: Vector2)
	if self._mode == "Phone" or self._window._draggable == false then
		return
	end
	self._window._positionWasDragged = true
	self._window._host.Position = UDim2.new(0.5, startOffset.X + delta.X, 0.5, startOffset.Y + delta.Y)
	self:ClampWindow()
end

function ResponsiveController:ClampMobileButton()
	local button = self._window._mobileToggle
	if not button or not button.Parent then
		return
	end
	local bounds = self._window._safeRoot.AbsoluteSize
	local size = button.AbsoluteSize
	if bounds.X <= 0 or bounds.Y <= 0 then
		return
	end
	local absolute = button.AbsolutePosition - self._window._safeRoot.AbsolutePosition
	local x = math.clamp(absolute.X, 10, math.max(10, bounds.X - size.X - 10))
	local y = math.clamp(absolute.Y, 10, math.max(10, bounds.Y - size.Y - 10))
	button.AnchorPoint = Vector2.zero
	button.Position = UDim2.fromOffset(x, y)
end

return ResponsiveController

end

__modules['Core/VisibilityController'] = function(__require)

local TweenUtil = __require("Utility/Tween")

local VisibilityController = {}
VisibilityController.__index = VisibilityController

function VisibilityController.new(window: any, visible: boolean): any
	local self = setmetatable({
		_window = window,
		_visible = visible,
		_transition = 0,
	}, VisibilityController)
	if not visible then
		window._safeRoot.Visible = false
		window._host.GroupTransparency = 1
		window._windowScale.Scale = 0.975
		window._backdrop.BackgroundTransparency = 1
	end
	self:_syncMobile()
	return self
end

function VisibilityController:_syncMobile()
	local window = self._window
	window._mobileToggle.Visible = window._mobileToggleEnabled
		and game:GetService("UserInputService").TouchEnabled
		and not self._visible
end

function VisibilityController:SetVisible(visible: boolean)
	if self._visible == visible or self._window._destroyed then
		return
	end
	self._visible = visible
	self._transition += 1
	local transition = self._transition
	local window = self._window
	local duration = window._theme.AnimationNormal
	if visible then
		window._safeRoot.Visible = true
		window._host.GroupTransparency = 1
		window._windowScale.Scale = 0.975
		window._backdrop.BackgroundTransparency = 1
		TweenUtil.Play(window._cleanup, window._host, duration, { GroupTransparency = 0 }, window:_reducedMotion())
		TweenUtil.Play(window._cleanup, window._windowScale, duration, { Scale = 1 }, window:_reducedMotion())
		TweenUtil.Play(window._cleanup, window._backdrop, duration, { BackgroundTransparency = window._backdropTransparency }, window:_reducedMotion())
	else
		TweenUtil.Play(window._cleanup, window._host, duration, { GroupTransparency = 1 }, window:_reducedMotion())
		TweenUtil.Play(window._cleanup, window._windowScale, duration, { Scale = 0.975 }, window:_reducedMotion())
		local tween = TweenUtil.Play(window._cleanup, window._backdrop, duration, { BackgroundTransparency = 1 }, window:_reducedMotion())
		if tween then
			tween.Completed:Once(function()
				if transition == self._transition and not self._visible and window._safeRoot.Parent then
					window._safeRoot.Visible = false
				end
			end)
		else
			window._safeRoot.Visible = false
		end
	end
	self:_syncMobile()
end

function VisibilityController:Toggle()
	self:SetVisible(not self._visible)
end

function VisibilityController:IsVisible(): boolean
	return self._visible
end

return VisibilityController

end

