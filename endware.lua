function Window:_buttonFeedback(
	button: GuiButton,
	normalToken: string,
	hoverToken: string,
	pressedToken: string?,
	locked: (() -> boolean)?,
	cleanupOverride: any?
)
	local cleanup = cleanupOverride or self._cleanup
	local hovering = false
	local pressing = false
	local function refresh()
		if locked and locked() then
			return
		end
		local token = normalToken
		if pressing and pressedToken then
			token = pressedToken
		elseif hovering then
			token = hoverToken
		end
		button.BackgroundColor3 = self._theme[token]
	end
	cleanup:Give(button.MouseEnter:Connect(function()
		hovering = true
		refresh()
	end))
	cleanup:Give(button.MouseLeave:Connect(function()
		hovering = false
		pressing = false
		refresh()
	end))
	cleanup:Give(button.InputBegan:Connect(function(inputObject: InputObject)
		if Input.IsPrimary(inputObject) then
			pressing = true
			refresh()
		end
	end))
	cleanup:Give(button.InputEnded:Connect(function(inputObject: InputObject)
		if Input.IsPrimary(inputObject) then
			pressing = false
			refresh()
		end
	end))
