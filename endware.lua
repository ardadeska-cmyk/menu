__modules['Utility/Create'] = function(__require)

local function Create(className: string, properties: {[string]: any}?, children: {Instance}?): any
	local instance = Instance.new(className)
	local dynamicInstance = instance :: any
	local parent: Instance? = nil
	if properties then
		for property, value in pairs(properties) do
			if property == "Parent" then
				parent = value
			else
				dynamicInstance[property] = value
			end
		end
	end
	if children then
		for _, child in ipairs(children) do
			child.Parent = instance
		end
	end
	if parent then
		instance.Parent = parent
	end
	return instance
end

return Create

end

__modules['Utility/Tween'] = function(__require)

local TweenService = game:GetService("TweenService")

local Tween = {}
local active: {[Instance]: Tween} = setmetatable({}, { __mode = "k" }) :: any

function Tween.Cancel(instance: Instance)
	local current = active[instance]
	if current then
		current:Cancel()
		active[instance] = nil
	end
end

function Tween.Play(
	cleanup: any,
	instance: Instance,
	duration: number,
	goal: {[string]: any},
	reducedMotion: boolean?,
	style: Enum.EasingStyle?,
	direction: Enum.EasingDirection?
): Tween?
	Tween.Cancel(instance)
	local dynamicInstance = instance :: any
	if reducedMotion or duration <= 0 then
		for property, value in pairs(goal) do
			dynamicInstance[property] = value
		end
		return nil
	end
	local tween = TweenService:Create(
		instance,
		TweenInfo.new(duration, style or Enum.EasingStyle.Quint, direction or Enum.EasingDirection.Out),
		goal
	)
	active[instance] = tween
	cleanup:Give(tween)
	cleanup:Give(tween.Completed:Connect(function()
		if active[instance] == tween then
			active[instance] = nil
		end
	end))
	tween:Play()
	return tween
end

return Tween

end

