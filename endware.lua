__modules['init'] = function(__require)

local Theme = __require("Theme")
local Window = __require("Core/Window")

local Endware = {}
Endware.Version = "0.2.0"
Endware.Themes = Theme.GetPresets()

function Endware.CreateTheme(overrides: {[string]: any}?): any
	return Theme.Create(overrides)
end

function Endware.new(options: any?): any
	return Window.new(options)
end

function Endware.CreateWindow(selfOrOptions: any, possibleOptions: any?): any
	local options = if possibleOptions ~= nil then possibleOptions else selfOrOptions
	if options == Endware then
		options = nil
	end
	return Endware.new(options)
end

return Endware

end

local function __require(name: string): any
	if __cache[name] ~= nil then
		return __cache[name]
	end
	assert(not __loading[name], string.format("[Endware] Circular bundled module dependency: %s", name))
	local loader = __modules[name]
	assert(loader ~= nil, string.format("[Endware] Bundled module %q was not found.", name))
	__loading[name] = true
	local result = loader(__require)
	__loading[name] = nil
	assert(result ~= nil, string.format("[Endware] Bundled module %q returned nil.", name))
	__cache[name] = result
	return result
end

return __require("init")
