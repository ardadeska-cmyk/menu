function Window:_safeCall(callback: ((...any) -> ())?, ...: any)
	if callback == nil then
		return
	end
	local packed = table.pack(...)
	local callable = callback :: any
	local ok, message = xpcall(function()
		callable(table.unpack(packed, 1, packed.n))
	end, debug.traceback)
	if not ok then
		warn("[Endware] Callback failed:\n" .. tostring(message))
	end
end

function Window:_reducedMotion(): boolean
	local ok, value = pcall(function()
		return GuiService.ReducedMotionEnabled
	end)
	return ok and value == true
end

function Window:_bind(instance: any, property: string, token: string, transform: ((any) -> any)?)
	local binding: Binding = {
		Instance = instance,
		Property = property,
		Token = token,
		Transform = transform,
	}
	table.insert(self._bindings, binding)
	instance.Destroying:Once(function()
		for index = #self._bindings, 1, -1 do
			if self._bindings[index] == binding then
				table.remove(self._bindings, index)
				break
			end
		end
	end)
	local value = self._theme[token]
	if transform then
		value = transform(value)
	end
	instance[property] = value
	return instance
end

function Window:_applyTheme()
	for index = #self._bindings, 1, -1 do
		local binding = self._bindings[index]
		local instance = binding.Instance
		if typeof(instance) ~= "Instance" or instance.Parent == nil then
			table.remove(self._bindings, index)
		else
			local value = self._theme[binding.Token]
			if binding.Transform then
				value = binding.Transform(value)
			end
			local ok = pcall(function()
				instance[binding.Property] = value
			end)
			if not ok then
				table.remove(self._bindings, index)
			end
		end
	end
	for _, tab in ipairs(self._tabs) do
		tab:_setActive(tab == self._activeTab)
	end
end

